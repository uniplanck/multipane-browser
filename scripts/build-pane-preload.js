// Builds src/pane-preload.js from src/pane-preload.template.js by putting the SHARED block of src/pane-rules.js where the template has
// its include line. The pane preload is sandboxed (no local require at runtime), so the shared rules are built in instead.
// Deterministic: same input -> same bytes (no dates, no absolute paths). Only Node built-ins.
//   node scripts/build-pane-preload.js           write src/pane-preload.js       (npm run build:preload)
//   node scripts/build-pane-preload.js --check   verify only, never writes; exit 1 when missing / out of date   (npm run check:preload)
// Also the electron-builder beforePack hook (package.json build.beforePack): packaging stops when the built preload is stale.
const fs = require('fs'), path = require('path');
const TEMPLATE = 'src/pane-preload.template.js', SHARED = 'src/pane-rules.js', OUT = 'src/pane-preload.js';
const SLOT = '// @include src/pane-rules.js\n', BEGIN = '// SHARED-BEGIN\n', END = '// SHARED-END\n';
const HEADER = `// GENERATED by scripts/build-pane-preload.js from ${TEMPLATE} + ${SHARED} - do not edit this file:\n` +
  '// edit those two, then run `npm run build:preload` (`npm run check:preload` verifies it is up to date).\n';
// offset of the one line that is exactly `s` (a whole line, not text inside a comment)
const line = (text, s, file) => { const k = '\n' + s, i = text.indexOf(k); if (i < 0 || text.indexOf(k, i + 1) >= 0) throw new Error(`${file}: needs exactly one line ${JSON.stringify(s.trim())}`); return i + 1; };
// template text + shared file text -> preload text
function render(template, shared) {
  template = template.replace(/\r\n/g, '\n'); shared = shared.replace(/\r\n/g, '\n');
  const a = line(shared, BEGIN, SHARED), b = line(shared, END, SHARED);
  if (b < a) throw new Error(`${SHARED}: SHARED-END before SHARED-BEGIN`);
  const block = shared.slice(a, b + END.length);
  if (/\brequire\s*\(|\bmodule\.|\bexports\b|\bprocess\./.test(block)) throw new Error(`${SHARED}: the shared block must not use require / module / exports / process (it runs in the sandboxed preload)`);
  const at = line(template, SLOT, TEMPLATE);
  return HEADER + template.slice(0, at) + block + template.slice(at + SLOT.length);
}
// -> exit code. root = the project directory (the parent of this script's folder)
function run(root, check) {
  let want;
  try { want = render(fs.readFileSync(path.join(root, TEMPLATE), 'utf8'), fs.readFileSync(path.join(root, SHARED), 'utf8')); } catch (e) { console.error('build-pane-preload:', e.message); return 2; }
  const out = path.join(root, OUT), have = fs.existsSync(out) ? fs.readFileSync(out) : null;
  if (have && have.equals(Buffer.from(want))) { console.log(`${OUT}: up to date`); return 0; }
  if (check) { console.error(`${OUT}: ${have ? 'out of date (or edited by hand)' : 'missing'} - edit ${TEMPLATE} / ${SHARED}, then run: npm run build:preload`); return 1; }
  fs.writeFileSync(out, want);
  console.log(`${OUT}: ${have ? 'updated' : 'written'}`);
  return 0;
}
const ROOT = path.join(__dirname, '..');
async function beforePack() { if (run(ROOT, true) !== 0) throw new Error(`${OUT} is missing or out of date: run npm run build:preload`); }
module.exports = { render, run, beforePack, TEMPLATE, SHARED, OUT };
if (require.main === module) process.exit(run(ROOT, process.argv.includes('--check')));
