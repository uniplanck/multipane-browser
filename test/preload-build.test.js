// node test/preload-build.test.js — scripts/build-pane-preload.js on copies in a temp directory: deterministic output, --check never writes
// and exits 1 when the built preload is missing / stale / edited by hand, one edit of the shared rules reaches main's copy and the preload,
// the beforePack hook stops packaging when stale; the committed preload is up to date and loads like a sandboxed preload.
const fs = require('fs'), os = require('os'), path = require('path'), cp = require('child_process');
const { loadPreload } = require('./preload-sandbox');
const ROOT = path.join(__dirname, '..'), SCRIPT = 'scripts/build-pane-preload.js';
const B = require('../' + SCRIPT);
let bad = 0; const t = (n, ok) => { if (!ok) bad++; console.log(ok ? 'ok  ' : 'FAIL', n); };
const throws = f => { try { f(); return false; } catch { return true; } };
const rejects = async f => { try { await f(); return false; } catch { return true; } };
const node = (root, ...args) => cp.spawnSync(process.execPath, [path.join(root, SCRIPT), ...args], { encoding: 'utf8' }).status;
(async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mpb-preload-'));
  try {
    // ---- the committed files ----
    const built = fs.readFileSync(path.join(ROOT, B.OUT), 'utf8');
    t('repo: src/pane-preload.js is up to date (--check exits 0)', node(ROOT, '--check') === 0);
    t('repo: marked as generated', built.startsWith('// GENERATED by scripts/build-pane-preload.js'));
    const pre = loadPreload();
    t('repo: loads as a plain script; requires only electron', pre.required.join() === 'electron');
    t('repo: no other require / eval / new Function', [...built.matchAll(/\brequire\s*\(\s*['"]([^'"]+)/g)].every(m => m[1] === 'electron') && !/\beval\s*\(|new Function/.test(built));
    t('repo: the shared functions are built in', ['markerOf', 'looksAsking', 'requestQuote', 'clipQuote', 'composerDraft'].every(k => typeof pre[k] === 'function'));
    const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
    t('package.json: npm start checks first', /build-pane-preload\.js --check/.test(pkg.scripts.prestart || ''));
    t('package.json: electron-builder beforePack is this script', path.resolve(ROOT, pkg.build.beforePack || '') === path.join(ROOT, SCRIPT) && typeof B.beforePack === 'function');
    t('package.json: packaged files include the built preload and the shared rules', pkg.build.files.includes('src/**/*'));
    // ---- copies in a temp directory ----
    for (const f of [SCRIPT, B.TEMPLATE, B.SHARED]) { fs.mkdirSync(path.join(tmp, path.dirname(f)), { recursive: true }); fs.copyFileSync(path.join(ROOT, f), path.join(tmp, f)); }
    const out = path.join(tmp, B.OUT), read = () => (fs.existsSync(out) ? fs.readFileSync(out) : null);
    const tb = require(path.join(tmp, SCRIPT));
    t('missing: --check exits 1', node(tmp, '--check') === 1);
    t('missing: --check wrote nothing', read() === null);
    t('missing: beforePack rejects', await rejects(() => tb.beforePack()));
    t('build exits 0', node(tmp) === 0);
    const first = read();
    t('built twice: same bytes', node(tmp) === 0 && read().equals(first));
    t('same bytes as the committed preload (no dates, no absolute paths)', first.equals(Buffer.from(built)));
    t('no temp / project path in the output', !first.toString().includes(tmp) && !first.toString().includes(ROOT));
    t('fresh: --check exits 0', node(tmp, '--check') === 0);
    t('fresh: beforePack resolves', !(await rejects(() => tb.beforePack())));
    // one edit of the shared rule
    const sh = path.join(tmp, B.SHARED), sh0 = fs.readFileSync(sh, 'utf8');
    fs.writeFileSync(sh, sh0.replace('const QUOTE_MAX = 300;', 'const QUOTE_MAX = 120;'));
    t('rule edited: --check exits 1', node(tmp, '--check') === 1);
    t('rule edited: --check left the preload untouched', read().equals(first));
    t('rule edited: beforePack rejects', await rejects(() => tb.beforePack()));
    t('rule edited: build exits 0, --check exits 0 again', node(tmp) === 0 && node(tmp, '--check') === 0);
    const long = 'あ'.repeat(500);
    t('rule edited: main side (require) has the change', require(sh).clipQuote(long).length === 120);
    t('rule edited: built preload has the change', loadPreload(out).clipQuote(long).length === 120);
    // the built preload edited by hand
    const edited = read();
    fs.appendFileSync(out, '// hand edit\n');
    t('hand edit: --check exits 1', node(tmp, '--check') === 1);
    t('hand edit: build restores it', node(tmp) === 0 && read().equals(edited));
    // broken inputs: error (exit 2), nothing written
    const tp = path.join(tmp, B.TEMPLATE), tp0 = fs.readFileSync(tp, 'utf8');
    fs.writeFileSync(tp, tp0.replace('\n// @include src/pane-rules.js\n', '\n'));
    t('template without the include line: exit 2, preload untouched', node(tmp) === 2 && read().equals(edited));
    fs.writeFileSync(tp, tp0);
    fs.writeFileSync(sh, sh0.replace('\n// SHARED-END\n', "\nconst fs = require('fs');\n// SHARED-END\n"));
    t('require in the shared block: exit 2, preload untouched', node(tmp) === 2 && read().equals(edited));
    t('render: two include lines', throws(() => B.render(tp0 + '// @include src/pane-rules.js\n', sh0)));
    t('render: no SHARED-BEGIN / SHARED-END line', throws(() => B.render(tp0, sh0.replace('\n// SHARED-BEGIN\n', '\n'))) && throws(() => B.render(tp0, sh0.replace('\n// SHARED-END\n', '\n'))));
    t('render: the marker words inside a comment are not markers', B.render(tp0, sh0.replace('\n// SHARED-BEGIN\n', '\n// SHARED-END is the closing line\n// SHARED-BEGIN\n')) === B.render(tp0, sh0));
    t('render: CRLF input gives the same output', B.render(tp0.replace(/\n/g, '\r\n'), sh0.replace(/\n/g, '\r\n')) === B.render(tp0, sh0));
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
  console.log(bad ? `${bad} failed` : 'all passed'); process.exit(bad ? 1 : 0);
})();
